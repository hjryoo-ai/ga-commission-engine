-- V105: Phase E1 — 아웃박스·이벤트 피드(설계서 §6.8, E1 지시문 D-1·D-2·D-17)
--   OUTBOX_EVENT : 업무 트랜잭션 안에서 seq 없이(NULL) 적재되는 포털 이벤트. append-only — 행을 고치는 일은 순번 부여 한 번뿐이다
--                  (Oracle은 V106 트리거가 그 밖의 UPDATE·DELETE를 거부한다. H2 티어는 저장소 포트에 그런 메서드가 없는 것으로).
--   OUTBOX_SEQ   : 한 행짜리 순번 표. 부여기가 이 행을 FOR UPDATE로 잠가 부여를 직렬화하고, 커밋된 미부여 행에만 last_seq + 1부터
--                  빈틈 없이 붙인다(Oracle SEQUENCE는 롤백·캐시로 갭이 나므로 쓰지 않는다 — 설계고찰 E1).
--   occurred_at은 피드에 나갈 문자열(ISO-8601 오프셋 포함) 그대로 — 바이트를 바꾸지 않는다.
--   번호: 전역 단조(docs/db-migrations.md) — V104 다음. 이식성: H2(MODE=Oracle)와 Oracle 19c+ 겸용.
-- =====================================================================

CREATE TABLE OUTBOX_EVENT (
    event_no       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       VARCHAR2(36)  NOT NULL,
    seq            NUMBER(19),
    event_type     VARCHAR2(40)  NOT NULL,
    schema_ver     NUMBER(3)     NOT NULL,
    aggregate_kind VARCHAR2(30)  NOT NULL,
    aggregate_id   VARCHAR2(64)  NOT NULL,
    occurred_at    VARCHAR2(40)  NOT NULL,
    payload        CLOB          NOT NULL,
    created_at     TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_outbox_event_id UNIQUE (event_id),
    CONSTRAINT uq_outbox_seq UNIQUE (seq),
    CONSTRAINT ck_outbox_seq_positive CHECK (seq IS NULL OR seq >= 1),
    CONSTRAINT ck_outbox_schema_ver CHECK (schema_ver >= 1)
);
CREATE INDEX ix_outbox_aggregate ON OUTBOX_EVENT (event_type, aggregate_kind, aggregate_id);

CREATE TABLE OUTBOX_SEQ (
    id       NUMBER(1)  PRIMARY KEY,
    last_seq NUMBER(19) NOT NULL,
    CONSTRAINT ck_outbox_seq_singleton CHECK (id = 1),
    CONSTRAINT ck_outbox_seq_last CHECK (last_seq >= 0)
);
INSERT INTO OUTBOX_SEQ (id, last_seq) VALUES (1, 0);
