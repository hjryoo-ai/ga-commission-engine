-- V107: Phase E1 — 지급명세 영속(설계서 §5.9·§7 ③, E1 계획 P6·승인 §2)
--   지급 런이 확정하는 세액·순액(PayoutService.PayoutStatement)은 지금까지 반환값과 배치 실행 컨텍스트에만 있었다 — 감사 대상 사실은
--   업무 테이블에 정본으로(부록 B-15). 정산 행(AGENT_SETTLEMENT) 하나에 지급명세 하나(UNIQUE). paid_at = 정산 행 기록·PAID 전이 시각
--   (주입된 시계 — 이체 실행 시각이 아니다, 포털 계약 v1.1.1 L2). PayoutCompleted 이벤트는 이 행을 저장한 뒤 같은 트랜잭션에서 발행된다.
--   번호: 전역 단조 — V106 다음. 이식성: H2(MODE=Oracle)와 Oracle 19c+ 겸용.
-- =====================================================================

CREATE TABLE PAYOUT_STATEMENT (
    payout_statement_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id       NUMBER        NOT NULL,
    close_ym            VARCHAR2(6)   NOT NULL,
    run_seq             NUMBER        NOT NULL,
    recipient_type      VARCHAR2(10)  NOT NULL,
    recipient_id        VARCHAR2(20)  NOT NULL,
    payable             NUMBER(15)    NOT NULL,
    income_tax          NUMBER(15)    NOT NULL,
    local_tax           NUMBER(15)    NOT NULL,
    net_pay             NUMBER(15)    NOT NULL,
    paid_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at          TIMESTAMP     DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_payout_statement_settlement UNIQUE (settlement_id),
    CONSTRAINT fk_payout_statement_settlement FOREIGN KEY (settlement_id) REFERENCES AGENT_SETTLEMENT (settlement_id),
    CONSTRAINT ck_payout_statement_recipient CHECK (recipient_type IN ('AGENT', 'ORG')),
    CONSTRAINT ck_payout_statement_run CHECK (run_seq >= 1)
);
CREATE INDEX ix_payout_statement_ym ON PAYOUT_STATEMENT (close_ym, run_seq);
