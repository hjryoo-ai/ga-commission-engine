package ga.comm.shadow;

/**
 * 섀도 런 차이 유형 (설계서 §8.5 — 대사 유형화(§7)의 재사용·확장). 병행 계산 전환 판단에 쓴다.
 */
public enum ShadowDiffType {
    /** 일치 (허용 오차 0원 기본 — 여기에만 clean). */
    MATCH,
    /** 미세 차 — 반올림 정책 차이 의심 (|차|이 반올림 허용폭 이내). */
    ROUNDING,
    /** 금액 차 — 요율/산식 차이 의심 (양쪽 다 존재, 반올림 폭 초과). */
    RATE_DIFF,
    /** 외부에만 존재 — 자체 계산 누락 (전환 시 놓친 계산). */
    MISSING,
    /** 자체 계산에만 존재 — 외부 미인지 또는 과다 계산. */
    UNEXPECTED,
    /** 같은 수급자×유형 금액이 다른 마감월에 잡힘 — 귀속 타이밍 차이. */
    TIMING
}
